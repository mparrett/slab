#!/usr/bin/env python3
"""vsco.py - fetch Versilian Studios Chamber Orchestra 2 Community Edition
and make it playable.

VSCO 2 CE (https://github.com/sgossner/VSCO-2-CE) is a CC0 / public-domain
orchestral library by the author of VCSL, with the same file naming:
string sections, solo strings, brass, woodwinds, a few keys. This script
reuses vcsl.py's mapping and measuring, and

  1. downloads it (pinned to one commit) into the Slab sample library,
     $SLAB_LIBRARY or ~/Music/Slab/Library, under vsco/samples/;
  2. writes an SFZ per instrument and articulation under vsco/<family>/;
  3. writes a sampler preset per SFZ into the pack, vsco/presets/sampler/,
     pointing at "lib:vsco/...".

Usage:
  tools/library/vsco.py --list                      instruments and sizes
  tools/library/vsco.py --only "Violin Section"     folders containing this
  tools/library/vsco.py --no-fetch                  regenerate from disk
"""
import argparse
import json
import os
import re
import sys
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vcsl  # noqa: E402

REPO = "sgossner/VSCO-2-CE"
COMMIT = "440300901dfe9275fd84e0b7763af1f8443ae62e"  # master, 2020-08-05
RAW = f"https://raw.githubusercontent.com/{REPO}/{COMMIT}/"
TREE = f"https://api.github.com/repos/{REPO}/git/trees/{COMMIT}?recursive=1"


def slug(folder):
    return re.sub(r"[^a-z0-9]+", "-", folder.split("/", 1)[-1].lower()).strip("-")


def family(folder):
    return "vsco-" + re.sub(r"[^a-z0-9]+", "-", folder.split("/")[0].lower()).strip("-")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", action="append", default=[], help="instrument path contains (repeatable)")
    ap.add_argument("--list", action="store_true", help="list instruments, fetch nothing")
    ap.add_argument("--no-fetch", action="store_true", help="use what's on disk")
    ap.add_argument("--jobs", type=int, default=8, help="parallel downloads")
    args = ap.parse_args()

    vcsl.TREE = TREE
    root = os.path.join(vcsl.library_root(), "vsco")
    tree = vcsl.fetch_tree(os.path.join(root, "tree.json"))
    insts, releases, files = vcsl.instruments(tree)

    only = [o.lower() for o in args.only]
    chosen = sorted(f for f in insts if not only or any(o in f.lower() for o in only))
    if args.list:
        for f in chosen:
            print(f"{sum(s for _, s in files[f]) / 1e6:8.1f} MB {len(insts[f]):4d}  {f}")
        print(f"{sum(sum(s for _, s in files[f]) for f in chosen) / 1e9:.2f} GB in {len(chosen)} instruments")
        return
    fetch = set(chosen) | {releases[f] for f in chosen if f in releases}
    if not args.no_fetch:
        vcsl.download([(RAW + urllib.request.quote(f"{f}/{n}"), os.path.join(root, "samples", f, n), sz)
                       for f in sorted(fetch) for n, sz in files[f]], args.jobs)

    def on_disk(f):
        return [n for n, _ in files[f] if os.path.exists(os.path.join(root, "samples", f, n))]

    cache_path = os.path.join(root, "analysis.json")
    analysis = json.load(open(cache_path)) if os.path.exists(cache_path) else {}
    if vcsl.np is not None:
        todo = [(f, n) for f in sorted(fetch) for n in on_disk(f) if f"{f}/{n}" not in analysis]
        for i, (f, n) in enumerate(todo):
            try:
                analysis[f"{f}/{n}"] = vcsl.measure(os.path.join(root, "samples", f, n), vcsl.parse(n)[0])
            except Exception as e:  # a broken file is skipped, not fatal
                print(f"\n  can't read {f}/{n}: {e}", file=sys.stderr)
        with open(cache_path, "w") as fh:
            json.dump(analysis, fh)

    made = []
    for f in chosen:
        names = on_disk(f)
        samples = [vcsl.Sample(f, n) for n in names]
        noted = [s for s in samples if s.midi is not None]
        if len(noted) < 3:
            continue
        rel = [vcsl.Sample(releases[f], n) for n in on_disk(releases[f])] if f in releases else []
        regions = vcsl.map_melodic(f, noted, analysis, rel)
        if not regions:
            continue
        b, s = family(f), slug(f)
        sfz = os.path.join(root, b, s + ".sfz")
        vcsl.write_sfz(sfz, f.replace("/", " / "), regions, root)
        with open(sfz) as fh:
            text = fh.read().replace("VCSL (CC0), https://github.com/sgossner/VCSL - generated by tools/library/vcsl.py",
                                     f"VSCO 2 CE (CC0), https://github.com/{REPO} - generated by tools/library/vsco.py")
        with open(sfz, "w") as fh:
            fh.write(text)
        layered = len({r[1].vel for r in regions}) > 1
        has_rel = any("trigger=release" in r[0] for r in regions)
        vcsl.write_preset(b, s, "VSCO 2 CE " + f.replace("/", " / "), f"lib:vsco/{b}/{s}.sfz",
                          vcsl.preset_params(f, "melodic", layered, has_rel), pack="vsco")
        made.append((b, s, len(regions)))

    with open(os.path.join(root, "README.txt"), "w") as fh:
        fh.write("Versilian Studios Chamber Orchestra 2 Community Edition, CC0 1.0 / public domain.\n"
                 f"https://github.com/{REPO} at {COMMIT}\n"
                 "samples/ is the library as published; the SFZ files beside it are generated by\n"
                 "Slab's tools/library/vsco.py. Slab presets refer to them as lib:vsco/...\n")
    for b, s, n in made:
        print(f"  {b}/{s}: {n} zones")
    print(f"{len(made)} instruments in {root}")


if __name__ == "__main__":
    main()
